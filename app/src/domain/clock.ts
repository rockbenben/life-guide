/**
 * 本机时钟：单调递增的毫秒数。
 *
 * ## 为什么不用 `Date.now()` 直接比大小
 *
 * 合并靠"谁新谁赢"（`updatedAt` 比大小）。直接用墙上时钟有两个洞：
 *
 * 1. **时钟往回走**（NTP 校时、用户改表、虚拟机恢复快照）：
 *    这台设备写的东西会比上一次还"旧" → 自己的改动被自己盖掉。
 * 2. **另一台设备的时钟快**（实测踩过：共享库里有一条"未来 1 秒"的时间戳，
 *    之后所有正常改动都被它压着）：那台写的东西排在很后面，
 *    这台之后的正常改动全部判成"更旧" → **改动凭空消失**。
 *
 * ## 这里怎么修
 *
 * - **单调**：本机每次取时间都至少比上一次大 1 毫秒（时钟往回走也不怕）；
 * - **吸收**：收到远端的数据时，把它的最大时间戳并进本机时钟 ——
 *   于是"我看见过的东西"之后，我的改动一定排在它后面。
 *
 * 这就是混合逻辑时钟（HLC）的核心：**保证因果序**。
 *
 * **它不能治的**：物理时钟本身就快的那台设备，它的记录仍然排在很后面
 * （这是任何基于时间的方案都躲不过的，除非换掉墙上时钟）。
 * 但只要两台设备同步过一次，因果序就建立了 —— 之后各自的改动不再互相吞掉。
 */

/** 计数器上限：同一毫秒内最多排 999 个改动。 */
export const TICK_MAX = 999;

export class TickClock {
  private last: number;

  constructor(initial = 0) {
    this.last = initial;
  }

  /** 本机此刻的时间戳：至少比上一次大 1。 */
  now(wall: number = Date.now()): number {
    const next = wall > this.last ? wall : this.last + 1;
    this.last = next;
    return next;
  }

  /**
   * 并进一个远端的时间戳（收到别人的数据时调用）。
   *
   * 并进来之后，本机之后的每一次改动都会排在它**后面** ——
   * 这就是"我看见过的东西不会把我的改动盖掉"。
   */
  absorb(ts: number): void {
    if (Number.isFinite(ts) && ts > this.last) this.last = ts;
  }

  /** 当前时钟值（存下来，下次启动接着用）。 */
  get value(): number {
    return this.last;
  }
}
